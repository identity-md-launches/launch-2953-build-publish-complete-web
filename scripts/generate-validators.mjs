import { readFile, writeFile, mkdir } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { createRequire } from "node:module";
import { dependency, loadDependency } from "./dependencies.mjs";
import { checkRuntime } from "./check-runtime.mjs";

export async function generateValidators({ check = false } = {}) {
  const Ajv2020 = loadDependency("ajv/dist/2020.js").default;
  const standalone = loadDependency("ajv/dist/standalone/index.js").default;
  const { _ } = loadDependency("ajv/dist/compile/codegen/index.js");
  const { build } = loadDependency("esbuild");
  // Bundle the helpers too: unbundled standalone output otherwise contains browser require().
  const helpers = await build({
    stdin: { contents: 'module.exports = {...require("ajv-formats/dist/formats.js").fullFormats, ...require("./scripts/validator-formats.cjs")};', resolveDir: process.cwd() },
    bundle: true, write: false,
    platform: "node", format: "cjs", logLevel: "silent",
    alias: { "ajv-formats": resolve(dependency("ajv-formats"), "../..") },
  });
  // esbuild retains CJS module labels. Normalize the optional scratch lookup location
  // so a normal npm ci and the contributor toolchain emit identical source bytes.
  const helperSource = helpers.outputFiles[0].text.replaceAll(
    "test/scratch/toolchain/node_modules/", "node_modules/",
  );
  const ajv = new Ajv2020({
    strict: false, allErrors: false, validateFormats: true,
    code: { source: true, formats: _`require("squeek-validator-formats")` },
  });
  // Load exactly the same functions that the standalone module will bundle.
  const formats = {
    ...loadDependency("ajv-formats/dist/formats.js").fullFormats,
    ...createRequire(import.meta.url)("./validator-formats.cjs"),
  };
  for (const [name, format] of Object.entries(formats)) ajv.addFormat(name, format);
  const names = {};
  for (const channel of ["status", "core", "events"]) {
    ajv.addSchema(JSON.parse(await readFile(`src/schemas/${channel}.json`, "utf8")), channel);
    names[channel] = channel;
  }
  const source = standalone(ajv, names);
  const result = await build({
    stdin: { contents: source, resolveDir: process.cwd(), sourcefile: "validators.cjs" },
    bundle: true, write: false, platform: "browser", format: "esm", target: "es2022",
    minify: true, logLevel: "silent",
    alias: { ajv: resolve(dependency("ajv"), "../..") },
    plugins: [{ name: "standalone-formats", setup(build) {
      build.onResolve({ filter: /^squeek-validator-formats$/ }, () => ({ path: "formats", namespace: "squeek" }));
      build.onLoad({ filter: /.*/, namespace: "squeek" }, () => ({ contents: helperSource, loader: "js" }));
    } }],
  });
  // esbuild's CJS entry exports a default object. Give the application typed named exports.
  const output = "// Generated by scripts/generate-validators.mjs. Do not edit.\n" +
    result.outputFiles[0].text.replace(/export default ([^;]+);?\s*$/, "const validators=$1;export const {status,core,events}=validators;\n");
  // Fail closed if a bundler upgrade changes the expected module shape or pulls in a compiler.
  checkRuntime(output, "validators.js");
  if (!output.includes("export const {status,core,events}")) throw new Error("Unexpected standalone module exports");
  const file = "src/generated/validators.js";
  if (check) {
    if (await readFile(file, "utf8") !== output) throw new Error("Generated validators are stale; run node scripts/build.mjs");
  } else {
    await mkdir("src/generated", { recursive: true });
    await writeFile(file, output);
  }
  console.log(`Standalone validators ${check ? "verified" : "generated"}: ${Buffer.byteLength(output)} bytes`);
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href)
  await generateValidators({ check: process.argv.includes("--check") });
